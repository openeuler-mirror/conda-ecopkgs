# coding=utf-8
"""
Test runner executed INSIDE the verification container.

Reads a test spec JSON (generated by update.py from packages/{pkg}/tests/cases.yml),
runs each case in the activated conda environment, and writes results in a
KunpengTest-compatible test_cases structure.

Usage: python test-runner.py <test-spec.json> <results-dir>

Exit codes:
    0 - all cases passed (pass/skip/blocked are acceptable)
    1 - at least one case failed or errored (CI must block the PR)
"""
import json
import os
import subprocess
import sys
import time
from datetime import datetime, timezone

OUTPUT_TAIL_LIMIT = 8000
MESSAGE_TAIL_LIMIT = 2000


def now_iso():
    return datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")


def tail(text, limit):
    text = (text or "").strip()
    return text[-limit:] if len(text) > limit else text


def run_case(case):
    """Run a single case and return a schema-compatible test case entry."""
    entry = {
        "name": str(case["name"]),
        "description": str(case.get("description") or case["name"]),
        "category": case.get("category", "functional"),
        "test_time": now_iso(),
    }

    if case.get("skip"):
        entry["result"] = "blocked" if case.get("blocked") else "skip"
        entry["message"] = case.get("message", "skipped by declaration")
        return entry

    timeout = int(case.get("timeout", 120))
    start = time.time()
    try:
        proc = subprocess.run(
            case["cmd"],
            shell=True,
            timeout=timeout,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            errors="replace",
        )
        entry["duration_ms"] = int((time.time() - start) * 1000)
        output = tail(proc.stdout, OUTPUT_TAIL_LIMIT)
        if proc.returncode == 0:
            entry["result"] = "pass"
            if output:
                entry["message"] = tail(output, MESSAGE_TAIL_LIMIT)
        else:
            entry["result"] = "fail"
            entry["message"] = output or f"exit code {proc.returncode}"
    except subprocess.TimeoutExpired as e:
        out = e.stdout or ""
        if isinstance(out, bytes):
            out = out.decode(errors="replace")
        entry["duration_ms"] = int((time.time() - start) * 1000)
        entry["result"] = "error"
        entry["message"] = f"timeout after {timeout}s. output tail: {tail(out, 4000)}"
    except Exception as e:  # infrastructure error, not a product failure
        entry["result"] = "error"
        entry["message"] = tail(str(e), 4000)
    return entry


def main():
    if len(sys.argv) < 3:
        print("Usage: python test-runner.py <test-spec.json> <results-dir>")
        return 2

    spec_path, results_dir = sys.argv[1], sys.argv[2]
    with open(spec_path, "r", encoding="utf-8") as f:
        spec = json.load(f)

    # expose context env vars so cases can branch on package/os/arch
    for key, value in spec.get("env", {}).items():
        os.environ[key] = str(value)

    results = []
    has_fail = False
    for case in spec.get("cases", []):
        entry = run_case(case)
        results.append(entry)
        print(f"[TEST] {entry['result']}: {entry['name']}")
        if entry["result"] in ("fail", "error"):
            has_fail = True

    os.makedirs(results_dir, exist_ok=True)
    out_path = os.path.join(results_dir, "test-results.json")
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(results, f, ensure_ascii=False, indent=2)
    print(f"[TEST] results written to {out_path}")

    return 1 if has_fail else 0


if __name__ == "__main__":
    sys.exit(main())
